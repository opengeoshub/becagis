def unaccent(text):
    try:
        text = text.replace("Đ", "D")  # For Vietnamese
        text = text.replace("đ", "d")  # For Vietnamese
    except NameError:
        pass
    result = (
        unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("utf-8")
    )
    return result


